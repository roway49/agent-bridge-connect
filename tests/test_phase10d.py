    def test_agent_final_callback_is_idempotent(self):
        self.service.start_task_run(self.task.id, "shell")
        first = self.service.finalize_task_from_agent(
            self.task.id,
            completed_callback(self.task, summary="first completion"),
        )
        second = self.service.finalize_task_from_agent(
            self.task.id,
            completed_callback(self.task, summary="duplicate completion"),
        )

        self.assertTrue(first)
        self.assertFalse(second)
        task = self.service.get_task(self.task.id)
        self.assertEqual(task.extensions["agentbc.final_callback"]["summary"], "first completion")
        finalized_events = [
            event
            for event in self.service.store.read_events(self.task.id)
            if event.get("event_type") == "task.finalized"
        ]
        self.assertEqual(len(finalized_events), 1)

