    def test_close_preserves_only_exact_latest_archive_receipt(self):
        task = self.service.create_task("close receipt", "codex", [{"id": 1, "description": "wait"}], customer_dir=False)
        self.service.record_executor_run_started(task.id, "run-first")
        bound = self.service.store.read_task(task.id)
        bound["extensions"]["agentbc.session"]["session_id"] = "exact-session"
        self.service.store.write_task(task.id, bound)
        self.service.record_executor_run_started(task.id, "run-latest")
        self.service.cancel_task(task.id)
        raw = self.service.store.read_task(task.id)
        raw["extensions"]["agentbc.close_intent"] = {"token": "close-test"}
        raw["extensions"]["agentbc.session"]["session_id"] = "exact-session"
        self.service.store.write_task(task.id, raw)
        receipt = {"version": 1, "executor": "codex", "session_id": "exact-session",
                   "resumed": True, "persistence": "persistent", "source": "jsonl_thread_started",
                   "archive_acknowledged": True, "archive_checked_at": "2026-10-09T15:33:16Z"}
        from agent_bridge_connect.protocol import ABCError
        for run_id, session_id in (("run-first", "exact-session"), ("run-latest", "wrong-session")):
            with self.subTest(run_id=run_id, session_id=session_id), self.assertRaises(ABCError):
                self.service.mark_task_needs_recovery(task.id, "interrupted", "late", executor_run_id=run_id,
                                                      execution_session={**receipt, "session_id": session_id})
            self.assertEqual(self.service.store.read_task(task.id), raw)
        self.assertFalse(self.service.mark_task_needs_recovery(task.id, "interrupted", "late",
                         executor_run_id="run-latest", execution_session=receipt))
        after = self.service.store.read_task(task.id)
        session = after["extensions"]["agentbc.session"]
        self.assertTrue(session["archive_acknowledged"])
        self.assertEqual(session["archive_checked_at"], receipt["archive_checked_at"])
        self.assertEqual(session["session_state"], "terminal")
        raw["extensions"]["agentbc.session"] = session
        self.assertEqual(after, raw)
        # Close reserves intent before cancellation commits its terminal state.
        after["status"] = "running"
        after["extensions"]["agentbc.session"].pop("archive_acknowledged")
        after["extensions"]["agentbc.session"].pop("archive_checked_at")
        self.service.store.write_task(task.id, after)
        self.assertFalse(self.service.mark_task_needs_recovery(task.id, "interrupted", "late",
                         executor_run_id="run-latest", execution_session=receipt))
        current = self.service.store.read_task(task.id)
        self.assertEqual(current["status"], "running")
        self.assertTrue(current["extensions"]["agentbc.session"]["archive_acknowledged"])


