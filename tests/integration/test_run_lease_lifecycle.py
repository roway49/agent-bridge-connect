class RunLeaseLifecycleTests(unittest.TestCase):
    def setUp(self):
        self.board = Path(tempfile.mkdtemp())
        self.config = {"workspace_root": str(self.board)}
        from agent_bridge_connect.service import TaskService

        self.service = TaskService(self.board, config=self.config)
        self.task = self.service.create_task("Phase 10d task", "shell", [{"id": 1, "description": "echo hello"}], customer_dir=False)

    def tearDown(self):
        shutil.rmtree(self.board)

    def _working_task(self):
        data = self.service.store.read_task(self.task.id)
        data["status"] = "working"
        self.service.store.write_task(self.task.id, data)

    def _lease(self, age_s=0):
        from agent_bridge_connect.run_lease import create_lease, save_lease

        lease = create_lease(self.task.id, "shell", os.getpid(), str(self.board))
        lease.last_heartbeat_at = (datetime.now(timezone.utc) - timedelta(seconds=age_s)).isoformat().replace("+00:00", "Z")
        save_lease(lease, self.board)
        return lease

    def test_status_and_list_leave_lost_lease_for_runner_maintenance(self):
        import threading
        from types import SimpleNamespace
        from agent_bridge_connect.cli import main
        from agent_bridge_connect.run_lease import maintain_runner_leases
        self._working_task()
        self._lease()
        before = self.service.store.read_task(self.task.id)
        with mock.patch("agent_bridge_connect.run_lease._process_lost", return_value=True):
            with mock.patch("agent_bridge_connect.cli._best_effort_desktop_route"), contextlib.redirect_stdout(io.StringIO()):
                self.assertEqual(main(["task", "status", self.task.id, "--root", str(self.board), "--json"]), 0)
            self.service.list_tasks()
            self.assertEqual(self.service.store.read_task(self.task.id), before)
            runner = SimpleNamespace(lock=threading.RLock(), known_boards={self.board})
            maintain_runner_leases(runner, now=100)
            recovered = self.service.store.read_task(self.task.id)
            self.assertEqual(recovered["status"], "needs_recovery")
            events = self.service.store.read_events(self.task.id)
            maintain_runner_leases(runner, now=111)
            self.assertEqual(self.service.store.read_task(self.task.id), recovered)
            self.assertEqual(self.service.store.read_events(self.task.id), events)

